import { describe, expect, it } from "vitest";
import {
  detectFigureTopic,
  examPrintsCurve,
  figureTopicOf,
  isCircuit,
  shouldDraw,
  topicText,
  wants3D,
  type FigureTopic,
} from "./figureTopic";

const draw = (
  topic: FigureTopic | null,
  modelAsked: boolean,
  questionText: string,
  subjectAllows = true,
  diagramAid = false,
) => shouldDraw({ topic, modelAsked, questionText, subjectAllows, diagramAid });

describe("FigureTopic", () => {
  it("complex from the question words", () => {
    expect(detectFigureTopic("Determine o afixo do número complexo z.")).toBe("complex");
    expect(detectFigureTopic("Represente z no plano complexo.")).toBe("complex");
  });

  it("space from an Oxyz frame", () => {
    expect(detectFigureTopic("No referencial o.n. Oxyz, considere o plano.")).toBe("space");
    expect(detectFigureTopic("A reta r passa por (1, 0, −2) e (0, 1, 3).")).toBe("space");
  });

  it("monotony and continuity", () => {
    expect(detectFigureTopic("Estude a monotonia e os extremos relativos de f.")).toBe("monotony");
    expect(detectFigureTopic("Mostre que f é contínua em x = 3.")).toBe("continuity");
  });

  it("no match is null", () => {
    expect(detectFigureTopic("Calcule o valor de 2 + 2.")).toBeNull();
  });

  it("trigonometry and forces", () => {
    expect(detectFigureTopic("No círculo trigonométrico, represente o ângulo de π/3.")).toBe("unitCircle");
    expect(detectFigureTopic("Determine o seno e o cosseno do ângulo α.")).toBe("unitCircle");
    expect(detectFigureTopic("Um corpo desce um plano inclinado com atrito.")).toBe("inclinedPlane");
    expect(detectFigureTopic("Represente as forças que atuam no corpo sobre a rampa.")).toBe("inclinedPlane");
  });

  it("a function graph is a function topic", () => {
    expect(detectFigureTopic("Esboce o gráfico da função f definida por f(x) = x^2 - 1.")).toBe("function");
    expect(detectFigureTopic("Estude a monotonia da função f.")).toBe("monotony");
  });

  it("complex still wins over a trigonometric form", () => {
    expect(detectFigureTopic("O número complexo z = e^{iθ} tem módulo 1.")).toBe("complex");
  });

  it("the solver's topic is used only when the rules say nothing", () => {
    expect(figureTopicOf("Calcule o valor de 2 + 2.", "space")).toBe("space");
    expect(figureTopicOf("Calcule o valor de 2 + 2.", "nonsense")).toBeNull();
    expect(figureTopicOf("Represente z no plano complexo.", "space")).toBe("complex");
  });

  it("a template is drawn unless the exam already prints the curve", () => {
    const parabola = "Na figura está representada parte do gráfico da função f, uma parábola.";
    expect(examPrintsCurve(parabola)).toBe(true);
    expect(draw("function", true, parabola)).toBe(false);
    expect(draw("complex", false, "Determine z².")).toBe(true);
    expect(draw("unitCircle", false, "Represente no círculo trigonométrico.")).toBe(true);
    expect(draw("inclinedPlane", false, "O corpo está sobre o plano inclinado.")).toBe(true);
    expect(draw("function", false, "Esboce o gráfico de f.")).toBe(true);
    expect(draw(null, true, "Um circuito simples.")).toBe(true);
    expect(draw("function", true, "f(x) = x.", false, true)).toBe(false);
    expect(examPrintsCurve("Na figura está representado um circuito.")).toBe(false);
  });

  it("volumes of revolution and circuits ask for the 3D figure", () => {
    const volume =
      "Calcule o volume do sólido de revolução obtido pela rotação, em torno do eixo Ox, da região limitada por y=sqrt(x), eixo Ox, x=4";
    expect(wants3D(volume)).toBe(true);
    expect(wants3D("Find the volume generated by rotating the region about the x-axis.")).toBe(true);
    expect(wants3D("No circuito elétrico da figura, determine a corrente.")).toBe(true);
    expect(wants3D("Esboce o gráfico de f.")).toBe(false);
    expect(wants3D("Calcule a área da região limitada por y = x².")).toBe(false);
    expect(draw("function", false, volume)).toBe(true);
  });

  /** The ICSE Q1 statement as the app read it before (math letters dropped, Ω as "W", values loose). */
  const icseQ1Scrambled =
    "Questão 1 − O circuito da figura, visto dos terminais a e b, é equivalente a uma\nresistência de valor:\nA.  = 6,5 Ω\na\nB.  = 21/13 Ω\n1 kW\nC.  = 3 Ω\n2 kW 1,5 kW\nD. Nenhuma das respostas anteriores\nb";

  it("scrambled circuit statements are circuits", () => {
    expect(isCircuit(icseQ1Scrambled)).toBe(true);
    expect(wants3D(icseQ1Scrambled)).toBe(true);
    expect(
      isCircuit(
        "Considere o circuito da figura e escolha os parâmetros que caracterizam o seu equivalente de Thévenin, visto dos terminais a-b.\n1 kW\n2 kW\n3 mA",
      ),
    ).toBe(true);
    expect(isCircuit("O gerador de tensão foi ligado há muito tempo. V1 = 20 V, L5 = 10 mH, R2 = 75 kΩ")).toBe(true);
    expect(isCircuit("Duas resistências de 4 Ω e 6 Ω estão ligadas em paralelo.")).toBe(true);
    expect(isCircuit("Find the equivalent resistance between terminals a and b.")).toBe(true);
    expect(isCircuit("A 10 μF capacitor charges through a 2 kΩ resistor from a 12 V battery.")).toBe(true);
  });

  it("not circuits", () => {
    expect(isCircuit("Considere a pilha implementada com uma lista ligada. Quantos nós tem?")).toBe(false);
    expect(isCircuit("Estude a natureza da série geométrica de razão 1/2.")).toBe(false);
    expect(isCircuit("Um projétil é lançado a 20 m/s; despreze a resistência do ar.")).toBe(false);
    expect(isCircuit("Uma lâmpada de 60 W está ligada durante 2 h. Qual a energia consumida?")).toBe(false);
    expect(isCircuit("Calcule o volume do sólido de revolução.")).toBe(false);
    expect(isCircuit("Questão 2 A. f(x) = x² B. g(x) = 2x")).toBe(false);
  });

  it("solids and surfaces ask for the 3D figure", () => {
    expect(wants3D("Calcule o volume do sólido limitado pelos planos coordenados e pelo plano 2x + 3y + z = 6.")).toBe(
      true,
    );
    expect(
      wants3D(
        "A base de um sólido é a região limitada por y = √x. As secções são semicírculos. Calcule o volume do sólido.",
      ),
    ).toBe(true);
    expect(wants3D("Esboce a superfície z = x² + y².")).toBe(true);
    expect(wants3D("Calcule o integral triplo de f sobre E.")).toBe(true);
    expect(wants3D("Um gás ocupa um volume de 2 L à pressão de 1 atm.")).toBe(false);
    expect(wants3D("Calcule a área da superfície lateral do cilindro.")).toBe(false);
  });

  it("a sibling question does not choose the figure", () => {
    const group = [
      "Grupo I Questões rápidas (4 val.)",
      "1. Duas esferas condutoras, de raios a e 2a, são ligadas por um fio condutor fino.",
      "2. Um dipolo eléctrico é formado por +q e −q a uma distância d.",
      "4. Um condensador C carregado a V0 é ligado em paralelo a um condensador igual, descarregado.",
    ].join("\n");
    const one = "1. Duas esferas condutoras, de raios a e 2a, são ligadas por um fio condutor fino.";
    expect(wants3D(group)).toBe(true);
    expect(wants3D(topicText(group, one, ["I.1", "I.2", "I.4"]))).toBe(false);
    const kirchhoff = [
      "Grupo VI Leis de Kirchhoff (2 val.)",
      "O ramo 1 tem a bateria V1 = 12 V em série com R1 = 2 Ω; o ramo 2 tem apenas R3 = 3 Ω.",
      "1. (0,75) Escreva a lei dos nós.",
      "2. (0,75) Determine i1, i2, i3.",
    ].join("\n");
    expect(isCircuit(topicText(kirchhoff, "2. (0,75) Determine i1, i2, i3.", ["VI.1", "VI.2"]))).toBe(true);
    // A lone question is read whole.
    expect(topicText(group, one, ["I.1"])).toBe(group);
  });
});
